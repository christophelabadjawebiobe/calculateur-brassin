create table if not exists public.categories (
  id          integer generated by default as identity primary key,
  code        text not null unique check (code in ('A','B','C','D')),
  libelle     text not null,
  description text
);
-- Classes de parts (statuts officiels) : A = Garant (fondateur), B = Personne physique, C = Institutionnel, D = Entreprise.
-- Rattrapage : une première version de ce script avait inversé C et D (C « Entreprises », D « Institutions ») ;
-- si c'est détecté, les fiches et les demandes déjà enregistrées sont basculées pour que leur sens reste correct.
do $$
declare idc integer; idd integer; ancien boolean;
begin
  select id into idc from public.categories where code = 'C';
  select id into idd from public.categories where code = 'D';
  ancien := exists (select 1 from public.categories where code = 'C' and libelle = 'Entreprises')
        and exists (select 1 from public.categories where code = 'D' and libelle = 'Institutions');
  if ancien then
    perform set_config('app.action', 'Correction des classes C/D (C = Institutionnel, D = Entreprise)', true);
    update public.cooperateurs set categorie_id = case categorie_id when idc then idd when idd then idc else categorie_id end where categorie_id in (idc, idd);
    if to_regclass('public.cooperateur_demandes') is not null then
      alter table public.cooperateur_demandes disable trigger trg_demandes_garde;
      update public.cooperateur_demandes set categorie_code = case categorie_code when 'C' then 'D' else 'C' end where categorie_code in ('C','D');
      alter table public.cooperateur_demandes enable trigger trg_demandes_garde;
    end if;
  end if;
exception when undefined_object then null;   -- première installation : rien à corriger
end $$;

