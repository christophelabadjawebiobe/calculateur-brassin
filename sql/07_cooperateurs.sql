-- ---------------------------------------------------------------------
-- 6. Sécurité (RLS) : lecture selon l'accès à l'application, écriture selon can_write_cooperateurs()
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['categories','parametres','cooperateurs','mouvements_parts','adresses','contacts','valorisations_annuelles','cooperateur_demandes','groupes_doublons','groupes_doublons_membres','journal','journal_contexte'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %1$s_select on public.%1$I', t);
    execute format('drop policy if exists %1$s_write on public.%1$I', t);
    execute format('drop policy if exists %1$s_ins on public.%1$I', t);
    execute format('drop policy if exists %1$s_upd on public.%1$I', t);
    execute format('drop policy if exists %1$s_del on public.%1$I', t);
    if t = 'journal' then
      execute 'create policy journal_select on public.journal for select to authenticated using (public.is_admin() or public.can_write_cooperateurs())';
    elsif t = 'journal_contexte' then
      execute 'create policy journal_contexte_select on public.journal_contexte for select to authenticated using (public.is_admin())';
      execute 'create policy journal_contexte_upd on public.journal_contexte for update to authenticated using (public.is_admin()) with check (public.is_admin())';
    else
      execute format('create policy %1$s_select on public.%1$I for select to authenticated using (public.can_read_cooperateurs())', t);
      execute format('create policy %1$s_ins on public.%1$I for insert to authenticated with check (public.can_write_cooperateurs())', t);
      execute format('create policy %1$s_upd on public.%1$I for update to authenticated using (public.can_write_cooperateurs()) with check (public.can_write_cooperateurs())', t);
      execute format('create policy %1$s_del on public.%1$I for delete to authenticated using (public.can_write_cooperateurs())', t);
    end if;
  end loop;
end $$;

