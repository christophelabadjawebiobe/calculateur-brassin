-- numéro de coopérateur déjà inscrit (même numéro national / d'entreprise, ou même e-mail) : rachat de parts
create or replace function public.coop_trouver_existant(p_numero text, p_email text) returns integer
language sql stable security definer set search_path = public as $$
  select id from (
    select c.id, 1 as pri from public.cooperateurs c
     where nullif(regexp_replace(coalesce(p_numero, ''), '\D', '', 'g'), '') is not null
       and c.numero_identification = regexp_replace(p_numero, '\D', '', 'g')
    union all
    select ct.cooperateur_id, 2 from public.contacts ct
     where ct.type = 'email' and nullif(trim(coalesce(p_email, '')), '') is not null and lower(trim(ct.valeur)) = lower(trim(p_email))
  ) x order by pri, id limit 1
$$;

-- calculs automatiques + verrouillage d'une demande validée
create or replace function public.demandes_garde() returns trigger
language plpgsql security definer set search_path = public as $$
declare ignore_cols text[] := array['odoo_mailing_synced','brevo_synced','certificat_genere','updated_at'];
begin
  if tg_op = 'DELETE' then
    if old.is_locked then raise exception 'Demande verrouillée : suppression impossible' using errcode = '42501'; end if;
    return old;
  end if;
  if tg_op = 'UPDATE' and old.is_locked and coalesce(current_setting('app.fusion', true), '') = '1' then
    return new;                                -- re-rattachement des demandes lors d'une fusion de fiches (fonction contrôlée)
  end if;
  if tg_op = 'UPDATE' and old.is_locked then
    if not new.is_locked and not public.is_admin() then
      raise exception 'Seul un administrateur peut déverrouiller une demande' using errcode = '42501';
    end if;
    if new.is_locked and (to_jsonb(new) - ignore_cols) is distinct from (to_jsonb(old) - ignore_cols) then
      raise exception 'Demande verrouillée (validée dans le registre) : modification impossible' using errcode = '42501';
    end if;
  end if;
  if tg_op = 'INSERT' and new.is_locked and not public.is_admin() then new.is_locked := false; end if;
  new.numero_national := nullif(regexp_replace(coalesce(new.numero_national, ''), '\D', '', 'g'), '');
  new.montant_total := new.nombre_parts * public.coop_valeur_part();
  if new.paiement_confirme and new.date_paiement is null then new.date_paiement := now(); end if;
  if not new.paiement_confirme and tg_op = 'UPDATE' and old.paiement_confirme then new.date_paiement := null; end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists trg_demandes_garde on public.cooperateur_demandes;
create trigger trg_demandes_garde before insert or update or delete on public.cooperateur_demandes for each row execute function public.demandes_garde();

-- ---------------------------------------------------------------------
-- 4. Journal d'audit (lecture seule) : tout est consigné par déclencheurs
--    journal_contexte(id=1).actif = false suspend la trace (import massif par un administrateur) ;
