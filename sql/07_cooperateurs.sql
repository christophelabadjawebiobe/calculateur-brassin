-- parts et capital par coopérateur
create or replace view public.v_parts_par_cooperateur with (security_invoker = true) as
  select c.id as cooperateur_id,
         coalesce(sum(m.nombre_parts), 0)::integer as total_parts,
         coalesce(sum(m.nombre_parts), 0) * public.coop_valeur_part() as capital,
         -- % du capital = parts du coopérateur / parts en circulation de la coopérative x 100
         round(case when sum(coalesce(sum(m.nombre_parts), 0)) over () > 0
                    then coalesce(sum(m.nombre_parts), 0) * 100.0 / sum(coalesce(sum(m.nombre_parts), 0)) over () else 0 end, 2) as pct_capital
    from public.cooperateurs c left join public.mouvements_parts m on m.cooperateur_id = c.id
   group by c.id;

-- valorisation annuelle : valeur comptable d'une part (formule de Sam)
--   capitaux propres = capital - capital non libéré + réserves + résultat reporté + résultat de l'exercice + subsides en capital
--   valeur comptable par part = capitaux propres / nombre de parts en circulation à la clôture
create table if not exists public.valorisations_annuelles (
  id                    integer generated by default as identity primary key,
  date_cloture          date not null unique,
  nombre_parts          integer not null check (nombre_parts > 0),
  valeur_nominale       numeric(12,2) not null,
  capital               numeric(14,2) not null,
  capital_non_libere    numeric(14,2) not null default 0,
  reserves              numeric(14,2) not null default 0,
  resultat_reporte      numeric(14,2) not null default 0,
  resultat_exercice     numeric(14,2) not null default 0,
  subsides_capital      numeric(14,2) not null default 0,
  capitaux_propres      numeric(14,2) not null,
  valeur_comptable_part numeric(14,4) not null,
  remarque              text,
  calcule_le            timestamptz not null default now()
);

-- parts en circulation à une date (registre)
create or replace function public.coop_parts_en_circulation(p_date date) returns integer
language sql stable security invoker set search_path = public as $$
  select coalesce(sum(nombre_parts), 0)::integer from public.mouvements_parts where date_mouvement is null or date_mouvement <= p_date
$$;

