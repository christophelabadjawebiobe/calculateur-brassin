-- clés de comparaison
create or replace function public.coop_cle_texte(p text) returns text
language sql immutable as $$
  select regexp_replace(translate(lower(coalesce(p, '')), 'àâäáãåçéèêëíìîïñóòôöõúùûüýÿœ', 'aaaaaaceeeeiiiinooooouuuuyyo'), '[^a-z0-9]', '', 'g')
$$;
create or replace function public.coop_cle_nom(p_nom text, p_prenom text) returns text
language sql immutable as $$
  select nullif(string_agg(t, ' ' order by t), '') from (
    select regexp_split_to_table(regexp_replace(translate(lower(coalesce(p_nom, '') || ' ' || coalesce(p_prenom, '')), 'àâäáãåçéèêëíìîïñóòôöõúùûüýÿœ', 'aaaaaaceeeeiiiinooooouuuuyyo'), '[^a-z0-9]+', ' ', 'g'), ' ') t
  ) x where t <> ''
$$;
create or replace function public.coop_cle_tel(p text) returns text
language sql immutable as $$
  select case when length(d) >= 8 then right(d, 8) end from (select regexp_replace(coalesce(p, ''), '\D', '', 'g') d) x
$$;

-- Détection : reconstruit les groupes « à traiter » ; les groupes déjà traités ou écartés (même composition) sont conservés
create or replace function public.detecter_doublons() returns jsonb
language plpgsql security definer set search_path = public as $$
declare changed boolean := true; n_new integer := 0; n_total integer := 0; g record; gid integer;
begin
  perform public.coop_exiger_ecriture();
  perform set_config('app.action', 'Détection des doublons', true);
  drop table if exists tmp_pairs; drop table if exists tmp_comp;
  create temp table tmp_pairs (a integer, b integer, kind text, raison text) on commit drop;
  -- e-mail
  insert into tmp_pairs select distinct least(x.cooperateur_id, y.cooperateur_id), greatest(x.cooperateur_id, y.cooperateur_id), 'email', 'Même e-mail : ' || lower(trim(x.valeur))
    from public.contacts x join public.contacts y on x.type = 'email' and y.type = 'email' and lower(trim(x.valeur)) = lower(trim(y.valeur)) and x.cooperateur_id < y.cooperateur_id
   where trim(x.valeur) <> '';
  -- téléphone
  insert into tmp_pairs select distinct least(x.cooperateur_id, y.cooperateur_id), greatest(x.cooperateur_id, y.cooperateur_id), 'tel', 'Même téléphone : ' || x.valeur
    from public.contacts x join public.contacts y on x.type = 'telephone' and y.type = 'telephone' and public.coop_cle_tel(x.valeur) = public.coop_cle_tel(y.valeur) and x.cooperateur_id < y.cooperateur_id
   where public.coop_cle_tel(x.valeur) is not null;
  -- nom + prénom (mots comparés sans ordre ni accents)
  insert into tmp_pairs select distinct x.id, y.id, 'nom', 'Même nom : ' || trim(concat(x.nom, ' ', x.prenom))
    from public.cooperateurs x join public.cooperateurs y on public.coop_cle_nom(x.nom, x.prenom) = public.coop_cle_nom(y.nom, y.prenom) and x.id < y.id
   where public.coop_cle_nom(x.nom, x.prenom) is not null;
  -- adresse (rue + numéro + code postal)
  insert into tmp_pairs select distinct least(x.cooperateur_id, y.cooperateur_id), greatest(x.cooperateur_id, y.cooperateur_id), 'adresse',
         'Même adresse : ' || trim(concat_ws(' ', x.rue, x.numero, x.code_postal, x.ville))
    from public.adresses x join public.adresses y on x.cooperateur_id < y.cooperateur_id
     and public.coop_cle_texte(x.rue) = public.coop_cle_texte(y.rue) and public.coop_cle_texte(x.numero) = public.coop_cle_texte(y.numero)
     and coalesce(x.code_postal, '') = coalesce(y.code_postal, '')
   where public.coop_cle_texte(x.rue) <> '' and public.coop_cle_texte(x.numero) <> '';
  -- composantes connexes
  create temp table tmp_comp (id integer primary key, comp integer) on commit drop;
  insert into tmp_comp select id, id from (select a as id from tmp_pairs union select b from tmp_pairs) z;
  while changed loop
    with m as (select c.id, least(c.comp, min(o.comp)) as nc from tmp_comp c
                 join (select a, b from tmp_pairs union all select b, a from tmp_pairs) e on e.a = c.id
                 join tmp_comp o on o.id = e.b group by c.id, c.comp)
    update tmp_comp c set comp = m.nc from m where c.id = m.id and m.nc < c.comp;
    changed := found;
  end loop;
  delete from public.groupes_doublons where statut = 'a_traiter';
  for g in
    select c.comp,
           array_agg(distinct c.id order by c.id) as membres,
           (select string_agg(distinct p.raison, ' · ' order by p.raison) from tmp_pairs p join tmp_comp cc on cc.id = p.a where cc.comp = c.comp) as raisons,
           (select least(100, coalesce(sum(w), 0)) from (select distinct p.kind, case p.kind when 'email' then 60 when 'tel' then 50 when 'nom' then 40 else 20 end as w
                 from tmp_pairs p join tmp_comp cc on cc.id = p.a where cc.comp = c.comp) k) as score,
           (select bool_or(p.kind <> 'adresse') from tmp_pairs p join tmp_comp cc on cc.id = p.a where cc.comp = c.comp) as probable
      from tmp_comp c group by c.comp
  loop
    n_total := n_total + 1;
    if exists (select 1 from (select groupe_id, array_agg(cooperateur_id order by cooperateur_id) m from public.groupes_doublons_membres group by groupe_id) e where e.m = g.membres) then continue; end if;
    insert into public.groupes_doublons (type, raisons, score) values (case when g.probable then 'doublon probable' else 'foyer possible' end, g.raisons, g.score) returning id into gid;
    insert into public.groupes_doublons_membres (groupe_id, cooperateur_id) select gid, unnest(g.membres);
    n_new := n_new + 1;
  end loop;
  return jsonb_build_object('groupes', n_total, 'nouveaux', n_new, 'a_traiter', (select count(*) from public.groupes_doublons where statut = 'a_traiter'));
end $$;

-- Statut d'un groupe (traité / écarté / à traiter) : consigné au journal
create or replace function public.statut_groupe_doublons(p_groupe integer, p_statut text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.coop_exiger_ecriture();
  if p_statut not in ('a_traiter','traite','ignore') then raise exception 'Statut invalide'; end if;
  perform set_config('app.action', 'Doublons : groupe ' || case p_statut when 'ignore' then 'écarté (ce ne sont pas des doublons)' when 'traite' then 'marqué traité' else 'rouvert' end, true);
  update public.groupes_doublons set statut = p_statut where id = p_groupe;
end $$;

-- Fusion contrôlée (comme Sam) : on choisit la fiche conservée, l'identité finale et les lignes à garder ;
-- les autres fiches du groupe sont supprimées. Tout est consigné (journal : suppression complète des fiches absorbées + événement détaillé).
drop function if exists public.fusionner_cooperateurs(integer, integer, jsonb, integer[], integer[], integer[]);
create or replace function public.fusionner_cooperateurs(
  p_groupe integer, p_garder integer, p_identite jsonb default '{}'::jsonb,
  p_mouvements integer[] default null, p_adresses integer[] default null, p_contacts integer[] default null,
  p_absorber integer[] default null          -- fiches à absorber (NULL = toutes les autres fiches du groupe)
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare ids integer[]; autres integer[]; k public.cooperateurs%rowtype; a record; c record; certs text := ''; n_mv integer := 0; n_ad integer := 0; n_ct integer := 0;
        nouveau_cert integer; id_txt text := ''; r record; rem text;
begin
  perform public.coop_exiger_ecriture();
  select array_agg(cooperateur_id order by cooperateur_id) into ids from public.groupes_doublons_membres where groupe_id = p_groupe;
  if ids is null or array_length(ids, 1) < 2 then raise exception 'Groupe introuvable ou incomplet'; end if;
  if not (p_garder = any(ids)) then raise exception 'La fiche conservée doit appartenir au groupe'; end if;
  select array_agg(i) into autres from unnest(ids) i where i <> p_garder and (p_absorber is null or i = any(p_absorber));
  if autres is null then raise exception 'Aucune fiche à absorber'; end if;
  ids := array_cat(array[p_garder], autres);
  perform set_config('app.action', 'Fusion de doublons (groupe ' || p_groupe || ')', true);
  perform set_config('app.fusion', '1', true);
  perform pg_advisory_xact_lock(70071);
  select * into k from public.cooperateurs where id = p_garder for update;
  select string_agg('fiche #' || id || coalesce(' (cert. n° ' || certificat, ' (sans certificat') || ', ' || trim(concat(nom, ' ', prenom)) || ')', ' ; ') into certs from public.cooperateurs where id = any(autres);
  -- 1. prises de parts : p_mouvements = lignes retenues (NULL = tout garder) ; les autres sont supprimées (tracées au journal)
  if p_mouvements is not null then delete from public.mouvements_parts where cooperateur_id = any(ids) and not (id = any(p_mouvements)); end if;
  update public.mouvements_parts set cooperateur_id = p_garder where cooperateur_id = any(autres); get diagnostics n_mv = row_count;
  -- 2. adresses
  if p_adresses is not null then delete from public.adresses where cooperateur_id = any(ids) and not (id = any(p_adresses)); end if;
  update public.adresses set cooperateur_id = p_garder, type = case when type = 'principale' and exists (select 1 from public.adresses x where x.cooperateur_id = p_garder and x.type = 'principale') then 'secondaire' else type end
   where cooperateur_id = any(autres); get diagnostics n_ad = row_count;
  -- 3. contacts (un seul principal par type, pas de doublon exact)
  if p_contacts is not null then delete from public.contacts where cooperateur_id = any(ids) and not (id = any(p_contacts)); end if;
  for c in select * from public.contacts where cooperateur_id = any(autres) order by principal desc, id loop
    if exists (select 1 from public.contacts x where x.cooperateur_id = p_garder and x.type = c.type and lower(trim(x.valeur)) = lower(trim(c.valeur))) then
      delete from public.contacts where id = c.id;
    else
      update public.contacts set cooperateur_id = p_garder, principal = c.principal and not exists (select 1 from public.contacts x where x.cooperateur_id = p_garder and x.type = c.type and x.principal) where id = c.id;
      n_ct := n_ct + 1;
    end if;
  end loop;
  -- 4. demandes de souscription rattachées aux fiches absorbées
  update public.cooperateur_demandes set cooperateur_id = p_garder where cooperateur_id = any(autres);
  update public.cooperateur_demandes set existing_coop_id = p_garder where existing_coop_id = any(autres);
  -- 5. suppression des fiches absorbées (journal : DELETE avec le contenu complet), puis identité finale de la fiche conservée
  delete from public.cooperateurs where id = any(autres);
  nouveau_cert := case when p_identite ? 'certificat' then nullif(p_identite->>'certificat', '')::integer else k.certificat end;
  rem := nullif(trim(coalesce(p_identite->>'remarques', k.remarques, '')), '');
  rem := trim(both ' ; ' from concat_ws(' ; ', rem, 'Fusion du ' || to_char(current_date, 'DD/MM/YYYY') || ' avec ' || certs));
  update public.cooperateurs set
     certificat = nouveau_cert,
     nom = coalesce(nullif(trim(p_identite->>'nom'), ''), nom),
     prenom = case when p_identite ? 'prenom' then nullif(trim(p_identite->>'prenom'), '') else prenom end,
     representant = case when p_identite ? 'representant' then nullif(trim(p_identite->>'representant'), '') else representant end,
     numero_identification = case when p_identite ? 'numero_identification' then nullif(regexp_replace(coalesce(p_identite->>'numero_identification', ''), '\D', '', 'g'), '') else numero_identification end,
     categorie_id = case when p_identite ? 'categorie_id' then nullif(p_identite->>'categorie_id', '')::integer else categorie_id end,
     remarques = rem
   where id = p_garder;
  update public.groupes_doublons set statut = 'traite' where id = p_groupe;
  update public.groupes_doublons g set statut = 'traite' where g.statut = 'a_traiter' and (select count(*) from public.groupes_doublons_membres m where m.groupe_id = g.id) < 2;
  insert into public.journal (utilisateur, action, operation, table_nom, enregistrement_id, cooperateur_id, libelle, apres)
  values (public.journal_utilisateur(), 'Fusion de doublons (groupe ' || p_groupe || ')', 'EVENEMENT', 'cooperateurs', p_garder::text, p_garder, trim(concat(k.nom, ' ', k.prenom)),
          jsonb_build_object('fiches_absorbees', certs, 'mouvements_deplaces', n_mv, 'adresses_deplacees', n_ad, 'contacts_deplaces', n_ct));
  return jsonb_build_object('cooperateur_id', p_garder, 'absorbees', coalesce(array_length(autres, 1), 0), 'mouvements', n_mv, 'adresses', n_ad, 'contacts', n_ct);
end $$;

