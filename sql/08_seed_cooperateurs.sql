-- ---- vérifications (une différence annule tout l'import) ----
do $$
declare n_coop integer; n_mv integer; n_adr integer; n_ct integer; parts integer; max_cert integer;
begin
  select count(*) into n_coop from public.cooperateurs;       select count(*) into n_mv from public.mouvements_parts;
  select count(*) into n_adr from public.adresses;            select count(*) into n_ct from public.contacts;
  select coalesce(sum(nombre_parts), 0) into parts from public.mouvements_parts; select coalesce(max(certificat), 0) into max_cert from public.cooperateurs;
  if n_coop <> 525 or n_mv <> 572 or n_adr <> 524 or n_ct <> 1047 or parts <> 2094 then
    raise exception 'Import incomplet : % fiches (attendu 525), % mouvements (attendu 572), % adresses, % contacts, % parts (attendu 2094)', n_coop, n_mv, n_adr, n_ct, parts;
  end if;
  if public.coop_valeur_part() <> '250'::numeric then raise exception 'La valeur de la part en base (%) diffère de la source (250)', public.coop_valeur_part(); end if;
  raise notice 'Import réussi : % fiches, % prises de parts (% parts en circulation, capital % EUR). Prochain certificat : n° %', n_coop, n_mv, parts, parts * public.coop_valeur_part(), max_cert + 1;
end $$;

