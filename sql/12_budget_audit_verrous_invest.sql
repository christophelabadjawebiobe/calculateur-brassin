create table if not exists public.budget_modifications_log (
  id            bigint generated by default as identity primary key,
  horodatage    timestamptz not null default now(),
  utilisateur_id uuid,
  utilisateur   text,
  annee         integer not null,
  scenario      text not null default 'base',
  scenario_titre text,
  type          text not null default 'modification' check (type in ('modification', 'creation', 'validation', 'suppression')),
  compte        text,                    -- clé du compte PCMN (6xxxxx / 7xxxxx)
  mois          integer check (mois between 1 and 12),   -- null = année entière (modification en masse ou changement non mensuel)
  ancien        numeric(14,2),
  nouveau       numeric(14,2),
  ecart         numeric(14,2),
  libelle       text
);
create index if not exists ix_bml_date on public.budget_modifications_log (horodatage desc);
create index if not exists ix_bml_plan on public.budget_modifications_log (annee, scenario);
create index if not exists ix_bml_user on public.budget_modifications_log (utilisateur);

create or replace function public.budget_log_lecture_seule() returns trigger
language plpgsql as $$ begin raise exception 'Le journal budgétaire est en lecture seule'; end $$;
drop trigger if exists trg_bml_readonly on public.budget_modifications_log;
create trigger trg_bml_readonly before update or delete on public.budget_modifications_log for each row execute function public.budget_log_lecture_seule();

create or replace function public.pcmn_plans_journal() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  o jsonb; n jsonb; k text; om numeric[]; nm numeric[]; i integer;
  cells jsonb := '[]'::jsonb; accts jsonb := '[]'::jsonb; ncell integer := 0; so numeric; sn numeric; chg boolean;
  u text := public.budget_utilisateur(); uid uuid := auth.uid(); r record; plan record;
begin
  if tg_op = 'DELETE' then
    insert into public.budget_modifications_log (utilisateur_id, utilisateur, annee, scenario, scenario_titre, type, libelle)
    values (uid, u, old.year, old.scenario, old.title, 'suppression', 'Budget supprimé');
    return old;
  end if;
  o := case when tg_op = 'UPDATE' then coalesce(old.data -> 'rows', '{}'::jsonb) else '{}'::jsonb end;
  n := coalesce(new.data -> 'rows', '{}'::jsonb);
  if tg_op = 'INSERT' then
    insert into public.budget_modifications_log (utilisateur_id, utilisateur, annee, scenario, scenario_titre, type, libelle)
    values (uid, u, new.year, new.scenario, new.title, 'creation', 'Budget créé');
  end if;
  if tg_op = 'UPDATE' and (new.is_locked is distinct from old.is_locked or new.validated_at is distinct from old.validated_at) then
    insert into public.budget_modifications_log (utilisateur_id, utilisateur, annee, scenario, scenario_titre, type, libelle)
    values (uid, u, new.year, new.scenario, new.title, 'validation',
            case when new.validated_at is not null or new.is_locked then 'Budget validé et verrouillé' else 'Validation retirée (budget déverrouillé)' end);
  end if;
  if tg_op = 'UPDATE' and new.data is not distinct from old.data then return new; end if;
  for k in select jsonb_object_keys(o || n) loop
    om := public.pcmn_entry_months(o -> k); nm := public.pcmn_entry_months(n -> k);
    so := 0; sn := 0; chg := false;
    for i in 1..12 loop
      so := so + om[i]; sn := sn + nm[i];
      if abs(nm[i] - om[i]) > 0.005 then
        chg := true; ncell := ncell + 1;
        cells := cells || jsonb_build_object('compte', k, 'mois', i, 'ancien', round(om[i], 2), 'nouveau', round(nm[i], 2));
      end if;
    end loop;
    if chg then accts := accts || jsonb_build_object('compte', k, 'mois', null, 'ancien', round(so, 2), 'nouveau', round(sn, 2)); end if;
  end loop;
  -- au-delà de 400 cellules (variation en %, import d'une année, duplication…) : une ligne par compte (année entière)
  for r in select * from jsonb_to_recordset(case when ncell > 400 then accts else cells end) as x(compte text, mois integer, ancien numeric, nouveau numeric) loop
    insert into public.budget_modifications_log (utilisateur_id, utilisateur, annee, scenario, scenario_titre, type, compte, mois, ancien, nouveau, ecart, libelle)
    values (uid, u, new.year, new.scenario, new.title, 'modification', r.compte, r.mois, r.ancien, r.nouveau, r.nouveau - r.ancien,
            case when ncell > 400 then 'Modification en masse (' || ncell || ' cellules)' else null end);
  end loop;
  return new;
end $$;
drop trigger if exists trg_pcmn_plans_journal on public.pcmn_budget_plans;
create trigger trg_pcmn_plans_journal after insert or update or delete on public.pcmn_budget_plans for each row execute function public.pcmn_plans_journal();

alter table public.budget_modifications_log enable row level security;
drop policy if exists bml_select on public.budget_modifications_log;
create policy bml_select on public.budget_modifications_log for select to authenticated using (public.has_app_access('/apps/budget'));
revoke all on public.budget_modifications_log from anon, authenticated;
grant select on public.budget_modifications_log to authenticated;

-- listes pour les filtres du journal
create or replace function public.budget_journal_filtres() returns jsonb
language sql stable security definer set search_path = public as $$
  select case when not public.has_app_access('/apps/budget') then '{}'::jsonb else jsonb_build_object(
    'budgets', coalesce((select jsonb_agg(jsonb_build_object('annee', annee, 'scenario', scenario, 'titre', t) order by annee, scenario)
                           from (select annee, scenario, max(scenario_titre) t from public.budget_modifications_log group by annee, scenario) z), '[]'::jsonb),
    'utilisateurs', coalesce((select jsonb_agg(utilisateur order by utilisateur) from (select distinct utilisateur from public.budget_modifications_log where utilisateur is not null) z), '[]'::jsonb)) end
$$;
grant execute on function public.budget_journal_filtres() to authenticated;

-- ---------------------------------------------------------------------
-- 2. Verrou d'édition (TTL 3 minutes, heartbeat toutes les ~40 s côté application)
-- ---------------------------------------------------------------------
create table if not exists public.budget_locks (
  year         integer not null,
  scenario     text not null default 'base',
  user_id      uuid,
  user_email   text,
  session_id   text not null,
  acquired_at  timestamptz not null default now(),
  heartbeat_at timestamptz not null default now(),
  expires_at   timestamptz not null,
  primary key (year, scenario)
);
alter table public.budget_locks enable row level security;
revoke all on public.budget_locks from anon, authenticated;     -- accès uniquement par les RPC ci-dessous

create or replace function public.budget_lock_take(p_year integer, p_scenario text, p_session text, p_force boolean default false)
returns jsonb language plpgsql security definer set search_path = public as $$
declare l public.budget_locks%rowtype; pu timestamptz; ttl interval := interval '3 minutes'; u text := public.budget_utilisateur();
begin
  if not public.can_write_budget() then return jsonb_build_object('ok', false, 'reason', 'droits'); end if;
  if p_session is null or length(p_session) < 8 then raise exception 'Identifiant de session invalide'; end if;
  select updated_at into pu from public.pcmn_budget_plans where year = p_year and scenario = p_scenario;
  select * into l from public.budget_locks where year = p_year and scenario = p_scenario for update;
  if not found or l.expires_at < now() or l.session_id = p_session or p_force then
    insert into public.budget_locks (year, scenario, user_id, user_email, session_id, acquired_at, heartbeat_at, expires_at)
    values (p_year, p_scenario, auth.uid(), u, p_session, now(), now(), now() + ttl)
    on conflict (year, scenario) do update set
      user_id = excluded.user_id, user_email = excluded.user_email,
      acquired_at = case when public.budget_locks.session_id = excluded.session_id and public.budget_locks.expires_at >= now() then public.budget_locks.acquired_at else now() end,
      session_id = excluded.session_id, heartbeat_at = now(), expires_at = now() + ttl;
    return jsonb_build_object('ok', true, 'plan_updated_at', pu, 'expires_at', now() + ttl);
  end if;
  return jsonb_build_object('ok', false, 'reason', 'verrou', 'holder', l.user_email, 'since', l.acquired_at, 'expires_at', l.expires_at, 'plan_updated_at', pu);
end $$;

create or replace function public.budget_lock_release(p_year integer, p_scenario text, p_session text) returns void
language sql security definer set search_path = public as $$
  delete from public.budget_locks where year = p_year and scenario = p_scenario and session_id = p_session
$$;
grant execute on function public.budget_lock_take(integer, text, text, boolean), public.budget_lock_release(integer, text, text) to authenticated;

-- garde : on ne remplace pas le contenu d'un budget dont le verrou vivant appartient à un autre utilisateur
create or replace function public.pcmn_plans_guard_lock() returns trigger
language plpgsql security definer set search_path = public as $$
declare l public.budget_locks%rowtype;
begin
  if new.data is distinct from old.data then
    select * into l from public.budget_locks where year = old.year and scenario = old.scenario and expires_at >= now();
    if found and l.user_id is distinct from auth.uid() then
      raise exception 'Budget en cours d''édition par % : enregistrement refusé (rechargez la page)', coalesce(l.user_email, 'un autre utilisateur') using errcode = '42501';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_pcmn_plans_lock on public.pcmn_budget_plans;
create trigger trg_pcmn_plans_lock before update on public.pcmn_budget_plans for each row execute function public.pcmn_plans_guard_lock();

