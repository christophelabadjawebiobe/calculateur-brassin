-- 12_budget_audit_verrous_invest.sql : Budget — journal des modifications, verrou d'édition, investissements et emprunts
-- À exécuter après 02, 04, 05 et 06 (idempotent, rejouable).
--   1. budget_modifications_log : journal (append-only) alimenté par un trigger sur pcmn_budget_plans (compte × mois, ancien → nouveau)
--   2. budget_locks + RPC budget_lock_take / budget_lock_release : verrou d'édition avec TTL (3 min) renouvelé par heartbeat
--      + trigger de garde : un autre utilisateur ne peut plus écraser un budget dont le verrou est vivant
--      (le contrôle optimiste par updated_at, déjà fait par l'application à l'enregistrement, reste le filet de sécurité)
--   3. budget_immobilisations (amortissements) et budget_emprunts (dettes) : base des calculs 630xxx / 650xxx
--   4. RPC budget_journal_filtres() : listes de valeurs pour les filtres du journal

-- ---------------------------------------------------------------------
-- 0. Outils
-- ---------------------------------------------------------------------
create or replace function public.budget_utilisateur() returns text
language plpgsql stable security definer set search_path = public as $$
declare e text;
begin
  begin e := nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'email'; exception when others then e := null; end;
  if e is null then begin select p.email into e from public.profiles p where p.id = auth.uid(); exception when others then e := null; end; end if;
  return coalesce(e, auth.uid()::text, 'système');
end $$;
grant execute on function public.budget_utilisateur() to authenticated;

-- mois d'une ligne du plan (même règle que l'application : mode annuel = montant / 12 ; sous-lignes additionnées)
create or replace function public.pcmn_leaf_months(l jsonb) returns numeric[]
language sql immutable as $$
  select case
    when l is null or jsonb_typeof(l) <> 'object' then array_fill(0::numeric, array[12])
    when coalesce(l->>'mode', 'annual') = 'annual' then array_fill(coalesce((l->>'annual')::numeric, 0) / 12, array[12])
    else array(select coalesce((l->'months'->>i)::numeric, 0) from generate_series(0, 11) i)
  end
$$;
create or replace function public.pcmn_entry_months(e jsonb) returns numeric[]
language plpgsql immutable as $$
declare r numeric[] := array_fill(0::numeric, array[12]); m numeric[]; s jsonb; i integer;
begin
  if e is null or jsonb_typeof(e) <> 'object' then return r; end if;
  if jsonb_typeof(e->'subs') = 'array' and jsonb_array_length(e->'subs') > 0 then
    for s in select * from jsonb_array_elements(e->'subs') loop
      m := public.pcmn_leaf_months(s);
      for i in 1..12 loop r[i] := r[i] + m[i]; end loop;
    end loop;
    return r;
  end if;
  return public.pcmn_leaf_months(e);
end $$;

