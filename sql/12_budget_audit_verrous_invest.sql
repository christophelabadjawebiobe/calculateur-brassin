create table if not exists public.budget_immobilisations (
  id            uuid primary key default gen_random_uuid(),
  libelle       text not null,
  date_service  date not null,                                   -- mise en service (seuls le mois et l'année comptent)
  duree_annees  numeric(5,2) not null check (duree_annees > 0 and duree_annees <= 60),
  montant_htva  numeric(14,2) not null check (montant_htva >= 0),
  methode       text not null default 'lineaire' check (methode in ('lineaire')),
  statut        text not null default 'existant' check (statut in ('existant', 'simulation')),
  inclus        boolean not null default true,                   -- pris en compte dans l'injection au budget (simulations)
  compte        text not null default '630200',                  -- compte PCMN de la dotation
  commentaire   text,
  created_by    uuid default auth.uid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create table if not exists public.budget_emprunts (
  id            uuid primary key default gen_random_uuid(),
  organisme     text not null,
  capital       numeric(14,2) not null check (capital > 0),
  mensualite    numeric(14,2) not null check (mensualite > 0),   -- principal + intérêts
  date_premiere_echeance date not null,
  date_fin      date not null,
  compte_interets text not null default '650000',
  commentaire   text,
  created_by    uuid default auth.uid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (date_fin >= date_premiere_echeance)
);
drop trigger if exists trg_bimm_updated on public.budget_immobilisations;
create trigger trg_bimm_updated before update on public.budget_immobilisations for each row execute function public.set_updated_at();
drop trigger if exists trg_bemp_updated on public.budget_emprunts;
create trigger trg_bemp_updated before update on public.budget_emprunts for each row execute function public.set_updated_at();

do $$
declare t text;
begin
  foreach t in array array['budget_immobilisations', 'budget_emprunts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %1$s_select on public.%1$I', t);
    execute format('drop policy if exists %1$s_ins on public.%1$I', t);
    execute format('drop policy if exists %1$s_upd on public.%1$I', t);
    execute format('drop policy if exists %1$s_del on public.%1$I', t);
    execute format('create policy %1$s_select on public.%1$I for select to authenticated using (public.has_app_access(''/apps/budget''))', t);
    execute format('create policy %1$s_ins on public.%1$I for insert to authenticated with check (public.can_write_budget())', t);
    execute format('create policy %1$s_upd on public.%1$I for update to authenticated using (public.can_write_budget()) with check (public.can_write_budget())', t);
    execute format('create policy %1$s_del on public.%1$I for delete to authenticated using (public.can_write_budget())', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

